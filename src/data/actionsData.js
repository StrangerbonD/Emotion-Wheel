// Helper: find which Core emotion & Secondary state any wheel emotion belongs to,
// and return the relevant Actions for that emotion.
export function getActionsForSelection(coreName, secondaryWord) {
  const group = EMOTION_ACTIONS[coreName];
  if (!group) return [];
  if (!secondaryWord) return group.actions;
  const matched = group.actions.filter((a) => a.states.includes(secondaryWord));
  return matched.length ? matched : group.actions;
}
